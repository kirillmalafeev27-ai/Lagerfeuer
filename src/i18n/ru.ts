/** «в полтора раза», «вдвое», «в 2,5 раза». */
function timesRu(mul: number): string {
  if (Math.abs(mul - 1.5) < 1e-9) return 'в полтора раза';
  if (Math.abs(mul - 2) < 1e-9) return 'вдвое';
  return `в ${String(Math.round(mul * 10) / 10).replace('.', ',')} раза`;
}

